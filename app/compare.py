"""Milestone 6: qualitative comparison -- N-gram vs base LLM vs LoRA-adapted LLM, side by side."""
import shutil
import textwrap
from pathlib import Path

DEFAULT_PROMPTS = [
    "The crowd",
    "He shoots and",
    "What a delivery from the bowler,",
    "Break point,",
    "The goalkeeper",
    "Fast break,",
]
COLUMNS = (("ngram", "N-gram"), ("base", "distilgpt2 (base)"), ("lora", "distilgpt2 + LoRA"))
NO_SPACE_BEFORE = tuple(".,!?;:")


def join_prompt(prompt: str, continuation: str) -> str:
    if not prompt:
        return continuation
    if not continuation:
        return prompt
    sep = "" if continuation.startswith(NO_SPACE_BEFORE) else " "
    return prompt + sep + continuation


def run_comparison(prompts: list[str], ngram_fn, base_fn, lora_fn) -> list[dict]:
    """Each *_fn takes a prompt and returns a continuation. Returns one row per prompt."""
    rows = []
    for p in prompts:
        rows.append({"prompt": p, **{key: join_prompt(p, fn(p)) for key, fn in
                                     (("ngram", ngram_fn), ("base", base_fn), ("lora", lora_fn))}})
    return rows


def render_side_by_side(rows: list[dict], width: int | None = None) -> str:
    """Three wrapped columns per prompt, for the terminal."""
    width = width or shutil.get_terminal_size((132, 24)).columns
    col = max(24, (width - 2 * 3) // 3)
    out = []
    for i, row in enumerate(rows, 1):
        out.append("=" * (col * 3 + 6))
        out.append(f"[{i}] prompt: {row['prompt']!r}")
        out.append("-" * (col * 3 + 6))
        wrapped = [textwrap.wrap(row[k], col) or [""] for k, _ in COLUMNS]
        out.append(" | ".join(title.ljust(col) for _, title in COLUMNS))
        out.append("-+-".join("-" * col for _ in COLUMNS))
        for j in range(max(len(w) for w in wrapped)):
            out.append(" | ".join((w[j] if j < len(w) else "").ljust(col) for w in wrapped))
    out.append("=" * (col * 3 + 6))
    return "\n".join(out)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def render_markdown(rows: list[dict], meta: dict, discussion: str = "") -> str:
    md = ["# Comparison: N-gram vs base distilgpt2 vs LoRA-adapted distilgpt2", ""]
    md += [f"Generated by `python -m app.cli compare`. Sampling: temperature {meta['temperature']}, top-k {meta['top_k']}, "
           f"seed {meta['seed']}, up to {meta['max_new_tokens']} new tokens. Every model sees the same prompts.", ""]
    md += ["## Setup", "", f"- N-gram: order n={meta['n']}, add-k smoothing (k={meta['k']}), backoff on unseen context.",
           f"- LLM: `{meta['model_name']}`; LoRA r={meta['r']}, alpha={meta['alpha']}, targets {meta['targets']}; "
           f"{meta['trainable']:,} trainable of {meta['total']:,} parameters ({meta['pct']:.3f}%).",
           "- Both models were trained on the same cleaned corpus (training split); perplexities use the held-out split.", ""]
    md += ["## Held-out numbers", "", "| model | metric | value |", "|---|---|---|"]
    md += [f"| N-gram (n={meta['n']}) | word-level perplexity | {meta['ngram_ppl']:.1f} |",
           f"| distilgpt2 (base) | token-level perplexity | {meta['base_ppl']:.1f} |",
           f"| distilgpt2 + LoRA | token-level perplexity | {meta['lora_ppl']:.1f} |", "",
           "Perplexities of the n-gram (word-level tokens) and the LLM (GPT-2 sub-word tokens) are **not** comparable with each "
           "other; the base-vs-LoRA pair is, and shows the adapter fits the commentary style.", ""]
    md += ["## Samples", ""]
    for i, row in enumerate(rows, 1):
        md += [f"### {i}. Prompt: `{row['prompt']}`", "", "| model | output |", "|---|---|"]
        md += [f"| {title} | {_cell(row[k])} |" for k, title in COLUMNS]
        md.append("")
    md += ["## Qualitative discussion", "", discussion.strip() or "_(no discussion written yet: add docs/discussion.md)_", ""]
    return "\n".join(md)


def load_discussion(path: str | Path) -> str:
    p = Path(path)
    return p.read_text(encoding="utf-8") if p.exists() else ""
