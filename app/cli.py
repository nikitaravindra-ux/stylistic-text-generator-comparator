"""Command-line entry point: `python -m app.cli --help`."""
import argparse
import json
from pathlib import Path

from app import core, finetune


def _add_model_args(p: argparse.ArgumentParser) -> None:
    p.add_argument("--model-name", default="distilgpt2", help='Hugging Face model id, or "tiny" for the offline test model')
    p.add_argument("--out-dir", default=str(core.OUT_DIR), help="where outputs/ (adapter, logs, report) go")


def _adapter(args) -> Path:
    return Path(args.out_dir) / "adapter" / "lora_adapter.pt"


def _sampling_args(p: argparse.ArgumentParser) -> None:
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--temperature", type=float, default=0.8)
    p.add_argument("--top-k", type=int, default=40)
    p.add_argument("--max-new-tokens", type=int, default=40)


def _train(args) -> dict:
    device = core.pick_device()
    print(f"device: {device}")
    model, tok = core.milestone_3(args.model_name, r=args.rank, alpha=args.alpha)
    model.to(device)
    hist = core.milestone_4(model, tok, epochs=args.epochs, batch_size=args.batch_size, lr=args.lr,
                            block_size=args.block_size, seed=args.seed, adapter_path=_adapter(args),
                            out_dir=args.out_dir, device=device)
    print("\n" + finetune.render_loss_curve(hist["step_loss"]))
    first, last = sum(hist["step_loss"][:5]) / 5, sum(hist["step_loss"][-5:]) / 5
    print(f"\ntrain loss {first:.3f} -> {last:.3f}; held-out loss {hist['val_loss'][0]:.3f} (base) -> {hist['val_loss'][-1]:.3f}")
    print(f"adapter saved to {_adapter(args)}")
    return hist


def _compare(args) -> None:
    model, tok = core.load_adapted_model(args.model_name, _adapter(args))
    ngram = core.milestone_2(n=args.n)
    print(core.milestone_6(model, tok, ngram, args.prompt or None, args.max_new_tokens, args.temperature, args.top_k,
                           args.seed, out_path=Path(args.out_dir) / "comparison.md", model_name=args.model_name))
    print(f"\nreport written to {Path(args.out_dir) / 'comparison.md'}")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="stylistic-text-generator-comparator", description="Sports journalists use this to compare text generated by a LoRA-adapted LLM with an N-gram model, both fine-tuned on specific sports commentary styles.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("hello", help="check that everything is wired up")

    sub.add_parser("corpus", help="milestone 1: clean the raw transcripts into corpus/clean.txt and print stats")

    p = sub.add_parser("ngram", help="milestone 2: build the n-gram model and sample from it")
    p.add_argument("-n", type=int, default=3, help="n-gram order")
    p.add_argument("--k", type=float, default=0.05, help="add-k smoothing constant")
    p.add_argument("--prompt", default="")
    p.add_argument("--samples", type=int, default=5)
    _sampling_args(p)

    def train_args(p):
        _add_model_args(p)
        p.add_argument("--epochs", type=int, default=8)
        p.add_argument("--batch-size", type=int, default=8)
        p.add_argument("--lr", type=float, default=1e-3)
        p.add_argument("--block-size", type=int, default=64)
        p.add_argument("--rank", type=int, default=8, help="LoRA rank r")
        p.add_argument("--alpha", type=float, default=16.0, help="LoRA alpha")
        p.add_argument("--seed", type=int, default=0)

    p = sub.add_parser("train", help="milestones 3+4: inject LoRA into the LLM and fine-tune it on the corpus")
    train_args(p)

    p = sub.add_parser("generate", help="milestone 5: generate from one model")
    _add_model_args(p)
    p.add_argument("--which", choices=["ngram", "base", "lora"], default="lora")
    p.add_argument("--prompt", default="")
    p.add_argument("-n", type=int, default=3)
    _sampling_args(p)

    p = sub.add_parser("compare", help="milestone 6: N-gram vs base vs LoRA side by side + outputs/comparison.md")
    _add_model_args(p)
    p.add_argument("--prompt", action="append", help="repeat for several prompts (default: a built-in set)")
    p.add_argument("-n", type=int, default=3)
    _sampling_args(p)

    p = sub.add_parser("all", help="run the whole pipeline: corpus -> n-gram -> train -> compare")
    train_args(p)
    p.add_argument("--prompt", action="append")
    p.add_argument("-n", type=int, default=3)
    p.add_argument("--temperature", type=float, default=0.8)
    p.add_argument("--top-k", type=int, default=40)
    p.add_argument("--max-new-tokens", type=int, default=40)

    args = parser.parse_args(argv)
    if args.command == "hello":
        print("Stylistic Text Generator Comparator is ready. Open README.md for your milestones.")
    elif args.command == "corpus":
        stats = core.milestone_1()
        print(json.dumps(stats, indent=2))
    elif args.command == "ngram":
        model = core.milestone_2(n=args.n, k=args.k)
        _, val = core.corpus.split_lines(core.corpus.load_corpus(core.CLEAN_PATH))
        print(f"{args.n}-gram model: vocab {len(model.vocab)}, held-out perplexity {model.perplexity(val):.1f}\n")
        for i in range(args.samples):
            text = model.generate(args.prompt, args.max_new_tokens, args.temperature, args.seed + i)
            print(f"[{i}] {(args.prompt + ' ' if args.prompt else '')}{text}")
    elif args.command == "train":
        _train(args)
    elif args.command == "generate":
        if args.which == "ngram":
            print(core.compare.join_prompt(args.prompt, core.milestone_2(n=args.n).generate(
                args.prompt, args.max_new_tokens, args.temperature, args.seed)))
        else:
            model, tok = core.load_adapted_model(args.model_name, _adapter(args))
            text = core.milestone_5(model, tok, args.prompt, args.max_new_tokens, args.temperature, args.top_k,
                                    args.seed, adapters=args.which == "lora")
            print(core.compare.join_prompt(args.prompt, text))
    elif args.command == "compare":
        _compare(args)
    elif args.command == "all":
        print("== milestone 1: corpus =="); print(json.dumps(core.milestone_1(), indent=2))
        print("\n== milestone 2: n-gram ==")
        ng = core.milestone_2(n=args.n)
        print(f"sample: {ng.generate('The crowd', seed=0)}")
        print("\n== milestones 3+4: LoRA fine-tune =="); _train(args)
        print("\n== milestones 5+6: generate and compare =="); args.seed = 0; _compare(args)


if __name__ == "__main__":
    main()
